const bySlug = new Map(posts.map((p) => [p.slug, p]));
const existing = await client.fetch('*[_type == "blogPostDocument"]{_id, "slug": slug.current}');
const slugToId = new Map(existing.map((d) => [d.slug, d._id]));

for (const post of posts) {
  const {related, ...fields} = post;
  const doc = {
    _type: 'blogPostDocument',
    status: 'published',
    ...fields,
    slug: {_type: 'slug', current: fields.slug},
    authors: [{name: 'Portals Production Research', role: 'Creative operations research'}],
  };
  const matchId = slugToId.get(post.slug);
  const result = matchId ? await client.patch(matchId).set(doc).commit() : await client.create(doc);
  slugToId.set(post.slug, result._id);
  console.log(`${matchId ? 'updated' : 'created'} ${post.slug}: ${result._id}`);
}

for (const post of posts) {
  const refs = (post.related || []).map((s) => bySlug.get(s)).filter(Boolean).map((r) => ({_type: 'reference', _ref: slugToId.get(r.slug)}));
  if (!refs.length) continue;
  await client.patch(slugToId.get(post.slug)).set({relatedPosts: refs}).commit();
  console.log(`linked ${post.slug} -> ${post.related.map((s) => s).join(', ')}`);
}
