import * as grpc from "@grpc/grpc-js";
import * as protoLoader from "@grpc/proto-loader";
import { fileURLToPath } from "node:url";

export interface UserInfo { userId: string; displayName: string }

/** Returned by `startAuthSession`: send the viewer to `loginUrl`, then poll
 *  `getAuthSession` with the `sessionCode` until it yields tokens. */
export interface AuthSessionStart { sessionCode: string; loginUrl: string }

/** A minted user credential. `refreshToken` is present only on session
 *  creation and refresh; it rotates on every refresh, so callers must persist
 *  the newest value or the next rotation fails as replay. */
export interface AuthSessionTokens {
  userToken: string;
  /** Epoch seconds when the user token expires, as issued by the gateway. */
  expiresAt: number;
  userId: string;
  userName: string;
  refreshToken?: string;
}

export interface AuthGatewayClient {
  verifyUser(token: string): Promise<UserInfo>;
  getUserInfo(resourceId: string, userId: string): Promise<UserInfo>;
  getUserId(resourceId: string, displayName: string): Promise<UserInfo>;
  /**
   * Begin a hosted sign-in. `clientState` must be a UUID generated by the
   * caller; it binds the session to the requester and is required again when
   * polling, so a different browser cannot consume the session.
   */
  startAuthSession(clientState: string): Promise<AuthSessionStart>;
  /**
   * Poll a session started with `startAuthSession`. Resolves `null` while the
   * viewer has not completed sign-in; resolves the minted tokens once they
   * have. The gateway consumes the session on success — only the first
   * successful poll receives tokens.
   */
  getAuthSession(sessionCode: string, clientState: string): Promise<AuthSessionTokens | null>;
  /**
   * Rotate a refresh credential for a new user token. The credential travels
   * in the `authorization` metadata key because the RPC request is empty by
   * contract. Resolves `null` when the gateway returns no token.
   */
  refreshAuthSession(refreshToken: string): Promise<AuthSessionTokens | null>;
  /**
   * Revoke the refresh credential's session family (sign-out). Best-effort:
   * the gateway never reveals whether the token existed.
   */
  revokeAuthSession(refreshToken: string): Promise<void>;
  close(): void;
}
export interface AuthGatewayClientConfig {
  address: string;
  /** Enable TLS outside a trusted private network. */
  useTls?: boolean;
  /** Per-call deadline in milliseconds, defaults to 5000. */
  timeout?: number;
  protoPath?: string;
}
type WireUser = { user_id: string; display_name: string };
type WireResponse = { user_info?: WireUser | WireUser[] };
type WireAuthSessionStart = { session_code?: string; login_url?: string };
type WireUserToken = {
  user_token?: string;
  expires_at?: string | number;
  user_id?: string;
  user_name?: string;
  refresh_token?: string;
};
type WireAuthSession = { user_token?: WireUserToken | null };

export function createAuthGatewayClient(config: AuthGatewayClientConfig): AuthGatewayClient {
  if (!config.address.trim()) throw new TypeError("Auth-gateway address is required.");
  const timeout = config.timeout ?? 5000;
  if (!Number.isFinite(timeout) || timeout <= 0) throw new TypeError("Timeout must be positive and finite.");
  const definition = protoLoader.loadSync(config.protoPath ?? fileURLToPath(new URL("./proto/auth_api.proto", import.meta.url)), {
    keepCase: true, longs: String, enums: String, defaults: true, oneofs: true,
  });
  const methods = definition["epic_urc.UrcAuthApi"] as protoLoader.ServiceDefinition;
  const descriptor = grpc.loadPackageDefinition(definition);
  const namespace = descriptor.epic_urc as grpc.GrpcObject;
  const Constructor = namespace.UrcAuthApi as grpc.ServiceClientConstructor;
  const client = new Constructor(config.address, config.useTls ? grpc.credentials.createSsl() : grpc.credentials.createInsecure());
  let closed = false;

  function unary<TResponse>(method: string, request: object, metadata?: grpc.Metadata): Promise<TResponse> {
    if (closed) return Promise.reject(new Error("Auth-gateway client is closed."));
    return new Promise<TResponse>((resolve, reject) => {
      client.makeUnaryRequest(`/epic_urc.UrcAuthApi/${method}`,
        (value: object) => methods[method].requestSerialize(value),
        (value: Buffer) => methods[method].responseDeserialize(value) as TResponse,
        request, metadata ?? new grpc.Metadata(), { deadline: Date.now() + timeout },
        (error, result: TResponse | undefined) => error ? reject(error) : resolve(result ?? ({} as TResponse)));
    });
  }

  async function call(method: string, request: object, expectedId?: string): Promise<UserInfo> {
    const response = await unary<WireResponse>(method, request);
    const candidates = Array.isArray(response.user_info) ? response.user_info : response.user_info ? [response.user_info] : [];
    const user = expectedId ? candidates.find((candidate) => candidate.user_id === expectedId) : candidates[0];
    if (!user || typeof user.user_id !== "string" || !user.user_id.trim() || typeof user.display_name !== "string") {
      throw new Error(`Auth-gateway ${method} returned no valid user info`);
    }
    return { userId: user.user_id, displayName: user.display_name };
  }

  /** The refresh credential rides in `authorization` metadata — the
   *  RefreshAuthSession and RevokeAuthSession requests are empty by contract. */
  function refreshMetadata(refreshToken: string): grpc.Metadata {
    const metadata = new grpc.Metadata();
    metadata.add("authorization", `Bearer ${refreshToken}`);
    return metadata;
  }

  function mapUserToken(response: WireAuthSession): AuthSessionTokens | null {
    const token = response.user_token;
    if (token === null || token === undefined) return null;
    if (typeof token.user_token !== "string" || !token.user_token.trim()) return null;
    const expiresAt = Number(token.expires_at);
    return {
      userToken: token.user_token,
      expiresAt: Number.isFinite(expiresAt) ? expiresAt : 0,
      userId: typeof token.user_id === "string" ? token.user_id : "",
      userName: typeof token.user_name === "string" ? token.user_name : "",
      ...(typeof token.refresh_token === "string" && token.refresh_token ? { refreshToken: token.refresh_token } : {}),
    };
  }

  return {
    verifyUser: (token) => call("VerifyUser", { target_user: { user_token: token }, requirements: [] }),
    getUserInfo: (resourceId, userId) => call("GetUserInfo", { resource_id: resourceId, user_id: [userId] }, userId),
    getUserId: (resourceId, displayName) => call("GetUserId", { resource_id: resourceId, user_display_name: displayName }),
    async startAuthSession(clientState) {
      const response = await unary<WireAuthSessionStart>("StartAuthSession", { client_state: clientState });
      if (typeof response.session_code !== "string" || !response.session_code.trim()
        || typeof response.login_url !== "string" || !response.login_url.trim()) {
        throw new Error("Auth-gateway StartAuthSession returned no usable session");
      }
      return { sessionCode: response.session_code, loginUrl: response.login_url };
    },
    getAuthSession: (sessionCode, clientState) =>
      unary<WireAuthSession>("GetAuthSession", { session_code: sessionCode, client_state: clientState })
        .then(mapUserToken),
    refreshAuthSession: (refreshToken) =>
      unary<WireAuthSession>("RefreshAuthSession", {}, refreshMetadata(refreshToken))
        .then(mapUserToken),
    revokeAuthSession: async (refreshToken) => {
      await unary<Record<string, never>>("RevokeAuthSession", {}, refreshMetadata(refreshToken));
    },
    close: () => { if (!closed) { closed = true; client.close(); } },
  };
}
